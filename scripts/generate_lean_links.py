#!/usr/bin/env python3
"""Generate declaration links from a committed Lean snapshot; never guess line numbers.

Commit formalization sources first, then run with --revision <commit>. The generated
TeX can be committed separately: its links keep pointing to the checked source commit.
"""
import argparse, hashlib, json, re, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def git(*args):
    return subprocess.check_output(['git', '-C', str(ROOT), *args], text=True).strip()

def declarations(text, path):
    blocks=[]; found={}
    # Preserve line numbers while discarding comments, including nested Lean block comments.
    depth=0; clean=[]
    for line in text.splitlines():
        out=''; i=0
        while i<len(line):
            if line[i:i+2]=='/-': depth+=1; i+=2
            elif depth and line[i:i+2]=='-/': depth-=1; i+=2
            elif depth: i+=1
            elif line[i:i+2]=='--': break
            else: out+=line[i]; i+=1
        clean.append(out)
    for number,line in enumerate(clean,1):
        match=re.match(r'^namespace\s+([\w.]+)',line)
        if match: blocks.append(('namespace',match[1])); continue
        match=re.match(r'^(?:noncomputable\s+)?section(?:\s+(\w+))?\s*$',line)
        if match: blocks.append(('section',match[1] or '')); continue
        if re.match(r'^end(?:\s+[\w.]+)?\s*$',line):
            if blocks: blocks.pop()
            continue
        # Private names have compiler-generated identifiers and are not public link targets.
        if re.match(r'^\s*(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+)?private\s+',line):
            continue
        match=re.match(r'^\s*(?:@\[[^\]]*\]\s*)?(?:(?:noncomputable|protected|private)\s+)*(theorem|lemma|def|abbrev|inductive|structure)\s+([\w.\']+)',line)
        if match:
            name='.'.join([b[1] for b in blocks if b[0]=='namespace']+[match[2]])
            found[name]={'path':path,'line':number,'kind':match[1]}
    return found

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--revision',required=True)
    ap.add_argument('--repo',default='https://github.com/JayPiZimmermann/A-Structural-Approach-to-Interpretable-Deep-Learning')
    ap.add_argument('--check',action='store_true')
    args=ap.parse_args()
    revision=git('rev-parse','--verify',args.revision+'^{commit}')
    paths=git('ls-tree','-r','--name-only',revision,'formalization').splitlines()
    decls={}
    for path in paths:
        if path.endswith('.lean') and '/.lake/' not in path and not path.endswith('/Audit.lean'):
            content=subprocess.check_output(['git','-C',str(ROOT),'show',revision+':'+path],text=True)
            if (ROOT/path).read_text()!=content:
                raise SystemExit(f'Lean source differs from pinned commit: {path}; commit it before linking')
            for name,data in declarations(content,path).items():
                if name in decls: raise SystemExit(f'Duplicate declaration: {name}')
                data['sha256']=hashlib.sha256(content.encode()).hexdigest()
                data['url']=f'{args.repo}/blob/{revision}/{path}#L{data["line"]}'
                decls[name]=data
    config=json.loads((ROOT/'formalization/tex_links.json').read_text())
    output=['% Generated by scripts/generate_lean_links.py; do not edit line numbers.',
            r'\newcommand{\leanrevision}{'+revision+'}',r'\newcommand{\leanbase}{'+args.repo+'/blob/'+revision+'}']
    results={}; theorem_number=0
    for label,spec in config.items():
        name=spec['declaration']
        if name not in decls: raise SystemExit(f'Unknown Lean declaration for {label}: {name}')
        data=decls[name]
        if not spec.get('equation'):theorem_number+=1
        number=0 if spec.get('equation') else theorem_number
        results[label]={**spec,**data,'reference_number':number}
        output.append(r'\DeclareLeanResult{'+label+'}{'+data['url'].replace('#', r'\#')+'}{'+name+'}{'+spec.get('display','Lean')+'}{'+str(number)+'}')
        if spec.get('equation'):
            output.append(r'\DeclareLeanEquation{'+label+'}{'+data['path']+'}{'+str(data['line'])+'}')
    outputs={ROOT/'tex/preamble/lean_links_generated.tex':'\n'.join(output)+'\n',
             ROOT/'formalization/lean_links.json':json.dumps({'revision':revision,'repository':args.repo,'links':results},indent=2)+'\n'}
    for path,content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text()!=content: raise SystemExit(f'Stale generated links: {path}')
        else: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
    print(f'{len(results)} links checked against {revision} ({len(decls)} declarations)')
if __name__=='__main__': main()
