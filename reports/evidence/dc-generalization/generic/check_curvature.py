#!/usr/bin/env python3
"""Render independent curvature contracts with the repository's exact checker."""
import importlib.util
import json
from pathlib import Path

EVIDENCE = Path(__file__).resolve().parent
ROOT = EVIDENCE.parents[3]
spec = importlib.util.spec_from_file_location("thesis_verify", ROOT / "formalization/scripts/verify.py")
verify = importlib.util.module_from_spec(spec)
spec.loader.exec_module(verify)
manifest = json.loads((EVIDENCE / "curvature-expected-types.json").read_text())
output = EVIDENCE / "curvature-exact"
output.mkdir(exist_ok=True)
source = "-- Generated by check_curvature.py from independently authored contracts.\n"
source += verify.exact_driver(manifest, output)
temporary = output / "ExactContracts.lean.tmp"
temporary.write_text(source)
temporary.replace(output / "ExactContracts.lean")
